
def generate_rag_response(query: str, context_chunks: list) -> dict:
    """
    Prepare retrieved document context and return a mock
    RAG response with source page citations.
    """

    # If retrieval returned nothing
    if not context_chunks:
        return {
            "answer": (
                "I could not find relevant information "
                "in the indexed document."
            ),
            "citations": [],
            "retrieved_snippets": [],
        }

    # Build context using retrieved chunks
    formatted_context = ""
    citations = []

    for chunk in context_chunks:
        page_num = chunk["page_number"]
        text_snippet = chunk["text"]

        formatted_context += (
            f"[Page {page_num}]: {text_snippet}\n\n"
        )

        if page_num not in citations:
            citations.append(page_num)

    # Prompt prepared for future LLM integration
    prompt = f"""
You are an Enterprise Document Assistant.

Answer the user's question using ONLY the
document context provided below.

If the context does not contain the answer,
say that you could not find the information.

Cite the page numbers used in your answer.

DOCUMENT CONTEXT:
{formatted_context}

USER QUESTION:
{query}
"""

    # MOCK response for today's implementation.
    # This is not generated by an LLM yet.
    synthesized_answer = (
        f"Retrieved information from pages "
        f"{', '.join(map(str, sorted(citations)))} "
        f"related to your question:\n\n"
        f"{context_chunks[0]['text'][:300]}"
    )

    return {
        "answer": synthesized_answer,
        "citations": sorted(citations),
        "retrieved_snippets": context_chunks,
    }
